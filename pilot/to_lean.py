"""Writes the pilot's sample as Lean data (lean/JSG/Pilot/Sample.lean) from the collector's
output, and our Comparator results.

usage: python3 pilot/to_lean.py DATA [--comparator RESULTS] > lean/JSG/Pilot/Sample.lean

It translates facts into Lean terms and decides nothing: grades, carry-over and verdicts are
JSG.Pilot.Core's. A Comparator result is a `RunResult`: accepted, rejected, a build error,
too large to check yet, or the kernels disagreeing. A challenge cut off or not started, or
with no result, hasn't run. Results count only from a results file marked trusted, which
pilot/shard_results.py writes. An untrusted run's results are measurements: the report names
them, and its challenges still count as not run. It fails if a dependency edge leaves the
sample, since dropping it silently could change a verdict.
"""
import argparse
import collections
import json
import sys
import textwrap

HEADER = """-- Generated by pilot/to_lean.py from {data}. Don't edit it by hand.
import JSG.Pilot.Core

/-!
The pilot's {label}: raw records of {n} manuscripts of openai/math at `{short}`
({repo}, {license}), collected by `pilot/collect.py`.
They hold only facts, and `JSG.Pilot.Core` turns them into grades.

{comparator}
-/

namespace JSG.Pilot.{name}

open JSG.Pilot
"""


# Each trusted result as its `RunResult`. cutOff and notStarted, which get a job of their own,
# and a challenge with no result, haven't run.
RUN_RESULTS = {"accepted": ".accepted", "rejected": ".rejected", "buildError": ".buildError",
               "tooLarge": ".tooLarge", "kernelsDisagree": ".kernelsDisagree"}

# How the report's note counts each result, in this order.
RESULT_WORDS = [
    ("accepted", lambda k: f"{k} {'was' if k == 1 else 'were'} accepted"),
    ("rejected", lambda k: f"{k} {'was' if k == 1 else 'were'} rejected"),
    ("tooLarge", lambda k: f"{k} {'was' if k == 1 else 'were'} too large to check yet"),
    ("buildError", lambda k: f"{k} ended in a build error"),
    ("kernelsDisagree", lambda k: f"on {k} the kernels disagreed"),
    ("cutOff", lambda k: f"{k} {'is' if k == 1 else 'are'} still to rerun"),
    ("notStarted", lambda k: f"{k} {'is' if k == 1 else 'are'} still to run"),
    ("notRun", lambda k: f"{k} {'has' if k == 1 else 'have'} no result yet"),
]


def lean_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lean_opt_str(s):
    return "none" if s is None else f"some {lean_str(s)}"


def lean_long_str(s, indent="    "):
    lines = textwrap.wrap(s, 80, drop_whitespace=False)
    return (" ++\n" + indent).join(lean_str(x) for x in lines)


def and_list(xs):
    return xs[0] if len(xs) == 1 else ", ".join(xs[:-1]) + " and " + xs[-1]


def vec(items, indent="    "):
    if not items:
        return "[]"
    return "[" + (",\n" + indent).join(items) + "]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("data")
    ap.add_argument("--comparator")
    ap.add_argument("--name", default="Sample")
    args = ap.parse_args()
    label = args.name.lower()
    sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    d = json.load(open(args.data, encoding="utf-8"))
    results, measured, run = {}, {}, None
    if args.comparator:
        c = json.load(open(args.comparator, encoding="utf-8"))
        # pilot/shard_results.py lists its runs; #83's measurements are a single run.
        runs = c["runs"] if "runs" in c else [c]
        run = and_list([f"[run {r['run']}]({r['url']})" for r in runs])
        if c.get("trusted") is True:
            results = c.get("results", {})
        else:
            measured = c.get("results", {})
    challenges = {c["name"]: c for c in d["challenges"]}
    ms = d["manuscripts"]
    index = {m["folder"]: i for i, m in enumerate(ms)}
    n = len(ms)

    def result(name):
        return RUN_RESULTS.get(results.get(name), ".notRun")

    raws, deps = [], []
    for m in ms:
        facts = ",\n        ".join(
            f"⟨{result(c)}, [{', '.join(lean_str(a) for a in challenges[c]['permittedAxioms'])}]⟩"
            for c in m["challenges"])
        raws.append(
            "{ withdrawnOn := " + lean_opt_str(m["withdrawnOn"]) + ",\n"
            "      challenges := [" + facts + "],\n"
            "      fidelityBy := none, reviewed := false, noveltyChecked := false,\n"
            "      depsRead := false }")
        targets = []
        for f in m["noticeLinks"]:
            if f not in index:
                sys.exit(f"to_lean.py: {m['folder']} links to {f}, which isn't in the {label}")
            targets.append(str(index[f]))
        deps.append("[" + ", ".join(targets) + "]")

    src = d["source"]
    names = list(dict.fromkeys(x for m in ms for x in m["challenges"]))
    if results:
        counts = collections.Counter(results.get(x, "notRun") for x in names)
        told = [phrase(counts[s]) for s, phrase in RESULT_WORDS if counts[s]]
        if not counts["rejected"]:
            told[-1] += "; none was rejected"
        comparator = (f"Comparator results come from our trusted shard runs, {run}. Of the "
                      f"{len(names)} challenges, " + and_list(told) + ". A build error, a "
                      "timeout or the kernels disagreeing leaves `formal_proof` unknown, "
                      "never failing.")
    elif measured:
        by = {}
        for x in names:
            if x in measured:
                by.setdefault(measured[x], []).append(f"`{x}`")
        parts = [("accepted " if s == "accepted" else f"ended '{s}' on ") + and_list(xs)
                 for s, xs in by.items()]
        comparator = (f"Comparator, in our {run}, " + "; ".join(parts) +
                      f". That run isn't trusted yet, since {c['why']}. So its results are "
                      "measurements, and no challenge counts as run.")
    else:
        comparator = "No Comparator result is recorded, so no challenge counts as run."
    note = lean_long_str(comparator)
    out = HEADER.format(data=args.data.replace("\\", "/"), n=n, label=label, name=args.name, short=src["commit"][:7],
                        repo=src["repository"], license=src["license"],
                        comparator=textwrap.fill(comparator, 95))
    folders = vec([lean_str(m["folder"]) for m in ms], "   ")
    titles = vec([lean_str(m["title"] or m["folder"]) for m in ms], "   ")
    families = vec([lean_opt_str(m["family"]) for m in ms], "   ")
    raw_terms = vec(raws, "   ")
    extra = ""
    if "earlierVersions" in d:
        pairs = [f"({lean_str(e['folder'])}, [{', '.join(lean_str(x) for x in e['listedAs'])}])"
                 for e in d["earlierVersions"]]
        extra += ("\n/-- Earlier versions of listed manuscripts, which aren't graded: each "
                  "folder, and the\n    listed folders of the same title. -/\n"
                  "def earlierVersions : List (String × List String) :=\n  [" +
                  ",\n   ".join(pairs) + "]\n")
        links = [f"({lean_str(m['folder'])}, {lean_str(m['docsLinks'])})"
                 for m in ms if "docsLinks" in m]
        extra += ("\n/-- Listed manuscripts whose family's docs page links an earlier "
                  "version: each folder,\n    and the folder the page links. -/\n"
                  "def docsLinks : List (String × String) :=\n  [" +
                  ",\n   ".join(links) + "]\n")
    dep_terms = vec(deps, "   ")
    out += f"""
/-- How many manuscripts the {label} has. -/
abbrev size : ℕ := {n}

/-- Each manuscript's folder under `preprints/`, in order. -/
def folders : List String :=
  {folders}

/-- Each manuscript's title, in order. -/
def titles : List String :=
  {titles}

/-- Each manuscript's family in `CONTENTS.md`, if it's listed there, in order. -/
def families : List (Option String) :=
  {families}

/-- Each manuscript's raw facts, in order. -/
def raws : List Raw :=
  {raw_terms}

/-- The manuscripts each one's withdrawal notice links to, in order. -/
def links : List (List (Fin size)) :=
  {dep_terms}

/-- A manuscript's folder under `preprints/`. -/
def folder : Fin size → String := nth folders (by decide +kernel)

/-- A manuscript's title. -/
def title : Fin size → String := nth titles (by decide +kernel)

/-- A manuscript's family in `CONTENTS.md`, if it's listed there. -/
def family : Fin size → Option String := nth families (by decide +kernel)

/-- Our Comparator runs on the {label}'s challenges, as the report states them. -/
def comparatorNote : String :=
  {note}

/-- The {label} as a release: each manuscript's raw facts, and the manuscripts its withdrawal
    notice links to. -/
def release : Release size where
  raw := nth raws (by decide +kernel)
  deps := nth links (by decide +kernel)
{extra}
end JSG.Pilot.{args.name}
"""
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
