"""Writes the pilot's sample as Lean data (lean/JSG/Pilot/Sample.lean) from the collector's
output, and our Comparator results.

usage: python3 pilot/to_lean.py DATA [--comparator RESULTS] > lean/JSG/Pilot/Sample.lean

It translates facts into Lean terms and decides nothing: grades, carry-over and verdicts are
JSG.Pilot.Core's. A Comparator result is "accepted" or "rejected"; anything else, a build
error or a run not yet made, is no result. It fails if a dependency edge leaves the sample,
since dropping it silently could change a verdict.
"""
import argparse
import json
import sys

HEADER = """-- Generated by pilot/to_lean.py from {data}. Don't edit it by hand.
import JSG.Pilot.Core

/-!
The pilot's sample: raw records of {n} manuscripts of openai/math at `{short}`
({repo}, {license}), collected by `pilot/collect.py`.
They hold only facts, and `JSG.Pilot.Core` turns them into grades.

{comparator}
-/

namespace JSG.Pilot.Sample

open JSG.Pilot
"""


def lean_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lean_opt_str(s):
    return "none" if s is None else f"some {lean_str(s)}"


def vec(items, indent="    "):
    if not items:
        return "![]"
    return "![" + (",\n" + indent).join(items) + "]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("data")
    ap.add_argument("--comparator")
    args = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    d = json.load(open(args.data, encoding="utf-8"))
    results = {}
    run = None
    if args.comparator:
        c = json.load(open(args.comparator, encoding="utf-8"))
        results = c.get("results", {})
        run = c.get("run")
    challenges = {c["name"]: c for c in d["challenges"]}
    ms = d["manuscripts"]
    index = {m["folder"]: i for i, m in enumerate(ms)}
    n = len(ms)

    def result(name):
        r = results.get(name)
        return {"accepted": "some true", "rejected": "some false"}.get(r, "none")

    raws, deps = [], []
    for m in ms:
        facts = ", ".join(
            f"⟨{result(c)}, [{', '.join(lean_str(a) for a in challenges[c]['permittedAxioms'])}]⟩"
            for c in m["challenges"])
        raws.append(
            "{ withdrawnOn := " + lean_opt_str(m["withdrawnOn"]) + ",\n"
            "      challenges := [" + facts + "],\n"
            "      fidelityBy := none, reviewed := false, noveltyChecked := false,\n"
            "      depsRead := false }")
        targets = []
        for f in m["noticeLinks"]:
            if f not in index:
                sys.exit(f"to_lean.py: {m['folder']} links to {f}, which isn't in the sample")
            targets.append(str(index[f]))
        deps.append("[" + ", ".join(targets) + "]")

    src = d["source"]
    comparator = ("Comparator results come from our pilot run" +
                  (f" {run}" if run else "") + "." if results else
                  "No Comparator result is recorded, so no challenge counts as run.")
    out = HEADER.format(data=args.data.replace("\\", "/"), n=n, short=src["commit"][:7],
                        repo=src["repository"], license=src["license"], comparator=comparator)
    folders = vec([lean_str(m["folder"]) for m in ms], "   ")
    titles = vec([lean_str(m["title"] or m["folder"]) for m in ms], "   ")
    families = vec([lean_opt_str(m["family"]) for m in ms], "   ")
    raw_terms = ",\n    ".join(raws)
    dep_terms = vec(deps, "    ")
    out += f"""
/-- How many manuscripts the sample has. -/
abbrev size : ℕ := {n}

/-- Each manuscript's folder under `preprints/`. -/
def folder : Fin size → String :=
  {folders}

/-- Each manuscript's title. -/
def title : Fin size → String :=
  {titles}

/-- Each manuscript's family in `CONTENTS.md`, if it's listed there. -/
def family : Fin size → Option String :=
  {families}

/-- The sample as a release: each manuscript's raw facts, and the manuscripts its withdrawal
    notice links to. -/
def release : Release size where
  raw := ![
    {raw_terms}]
  deps := {dep_terms}

end JSG.Pilot.Sample
"""
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
